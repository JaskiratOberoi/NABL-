  "Legend; “√ ” – Authorized      “X” - Not Authorized      “+” - If required or in absence of another staff";

/** Shared shape of the three authorization forms. */
function authorizationForm(
  id: string,
  suffix: string,
  pageOfClause: number,
  sourcePage: number,
  labels: string[],
): FormSpec {
  return {
    id,
    title: `AUTHORIZATION FORM – ${suffix}`,
    recordingSchedule: "(Recording schedule – Yearly)",
    clause: "6.2",
    pageOfClause,
    sourcePage,
    sourcePageSize: "Letter",
    orientation: "portrait",
    sheetPeriod: "month",
    headerFields: [
      { key: "name", label: "Name:" },
      { key: "designation", label: "Designation" },
      { key: "year", label: "Year:" },
      { key: "department", label: "Department" },
    ],
    bands: [
      {
        key: "activities",
        heading: "",
        layout: "authGrid",
        cadence: "yearly",
        pairColumns: 3,
        cell: "text",
        rows: activities(labels),
      },
      {
        key: "approval",
        heading: "",
        layout: "fields",
        cadence: "yearly",
        rows: [],
        fields: [
          { key: "approvedBy", label: "Approved by", cell: "initial", width: 0.5 },
        ],
      },
    ],
    legend: AUTH_LEGEND,
  };
}

