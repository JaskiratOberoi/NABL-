import type { ActivityRow, FormSpec } from "../types";

/**
 * Clause 6.2 personnel record formats.
 *
 * These differ in kind from the schedules of clauses 6.3 and 6.4: each is a
 * record about one member of staff, or one training event, rather than a month
 * of days. Most are built from labelled fields, prose and simple ledgers.
 */

/** Turns a plain list of activity names into rows. */
function activities(labels: string[], prefix = "a"): ActivityRow[] {
  return labels.map((label, i) => ({ key: `${prefix}${i + 1}`, label }));
}

